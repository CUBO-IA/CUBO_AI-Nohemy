# boolean.py
# BOOLEAN (bool) - True or False

# 1. Creating booleans
is_student = True
is_raining = False

print(is_student)
print(is_raining)

# 2. Comparisons produce booleans
age = 16

print(age > 18)
print(age == 16)
print(age != 20)
print(age <= 16)

# 3. Logical operators
has_ticket = True
has_money = False

print(has_ticket and has_money)
print(has_ticket or has_money)
print(not has_ticket)

# 4. Check the data type
print(type(is_student))

