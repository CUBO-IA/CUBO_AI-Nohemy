# int.py
# INTEGER (int) - whole numbers

# 1. Creating integers
age = 16
year = 2026
negative_number = -10

print("Age:", age)
print("Year:", year)
print("Negative:", negative_number)

# 2. Arithmetic with integers
a = 10
b = 3

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)       # This returns a float
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

# 3. Check the data type
print(type(age))

